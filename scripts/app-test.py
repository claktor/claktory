#!/usr/bin/env python3
"""Runs the app's whole Flutter test suite in a few bundles instead of one
compile per file.

    heavy scripts/app-test.py [--bundles N] [flutter test options…]

`flutter test` compiles every test file into a kernel of its own and starts
a test process for it: about 200 MB written per file, ~70 GB for a full run
of the app's ~380 files (Polpo's study). This writes one entry file per
bundle into app/test/.bundles/ (not tracked), each importing its share of
the test files and running each file's main() in a group named after it,
and runs those: a few GB.

One file while you work is as before, unbundled:

    cd app && flutter test test/usage_test.dart

Files in a bundle share a process, so what one leaves behind (an app-wide
listener, a debug variable a failed test didn't put back, fonts it loaded)
the next file sees, and a test can fail there that passes on its own. So
the result is always the per-file one: every file with a failure in its
bundle runs again on its own, as all of them used to, and its result there
counts. The summary at the end says which files ran again and why.

Bundles are kept apart by what changes a whole process, so that's rare:
- plain_*: files with no widget tests. Flutter's test binding, once any
  file starts it, answers every HTTP request with 400 and makes a
  ChangeNotifier used after dispose throw a FlutterError instead of a
  StateError, so these never share a process with a widget test.
- fonts: files that load real fonts, which then stay loaded and change
  every later file's text sizes.
- widgets_*: the rest. Each file starts with the test window's sizes, text
  scale and the like as a new process has them.
A file goes to a bundle by a hash of its path, so a bundle's files stay the
same as files grow, and a new file joins one.

A file that can never share a process says so in a line of its own,

    // test-bundle: alone (why)

and runs on its own; so do the files in ALONE below.

Options go to `flutter test` (--concurrency 2 unless given).
"""

import json
import os
import re
import subprocess
import sys
import tempfile
import zlib

# Files that need a process of their own, and why. A file that fails in a
# bundle and passes alone runs again anyway; listing it saves the noise and
# the bundle's time.
ALONE = {
    # Checks that it never starts a Flutter binding.
    'test/android/device_identity_unbound_test.dart',
    # Move the lifecycle in steps an app-wide AppLifecycleListener (made by
    # an earlier file, such as e2ee's) refuses: resumed to paused, paused
    # to resumed.
    'test/android/background_connection_test.dart',
    'test/android/back_host_test.dart',
    # Failed beside other files and passed on their own in the trial runs;
    # the cause isn't known yet.
    'test/ipad/ink_bridge_test.dart',
    'test/ipad/sidebar_large_text_test.dart',
    'test/move_test.dart',
}

APP = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app')
OUT = 'test/.bundles'


def bundle_files(widget_bundles):
    """Writes the bundles; returns {bundle path: [test files]} and the
    files that run alone."""
    os.makedirs(OUT, exist_ok=True)
    for name in os.listdir(OUT):
        os.remove(os.path.join(OUT, name))
    files = []
    for root, dirs, names in os.walk('test'):
        dirs[:] = sorted(d for d in dirs if not d.startswith('.'))
        files += [os.path.join(root, n) for n in names if n.endswith('_test.dart')]
    files.sort()

    groups, alone = {}, []
    for path in files:
        text = open(path, encoding='utf-8').read()
        if path in ALONE or re.search(r'^// test-bundle: alone', text, re.M):
            alone.append(path)
            continue
        if re.search(r'FontLoader|loadFontFromList', text):
            bundle = 'fonts'
        elif re.search(r'testWidgets|ensureInitialized|TestWidgetsFlutterBinding', text):
            bundle = 'widgets_%d' % (zlib.crc32(path.encode()) % widget_bundles)
        else:
            bundle = 'plain_%d' % (zlib.crc32(path.encode()) % 2)
        groups.setdefault(bundle, []).append(path)

    bundles = {}
    for bundle, paths in sorted(groups.items()):
        widgets = not bundle.startswith('plain')
        lines = ["// Generated by scripts/app-test.py: don't edit.",
                 "import 'package:flutter_test/flutter_test.dart';"]
        lines += ["import '../%s' as t%d;" % (p[len('test/'):], i)
                  for i, p in enumerate(paths)]
        lines += ['', 'void main() {']
        for i, p in enumerate(paths):
            lines += ["  group('%s', () {" % p[len('test/'):],
                      '    setUpAll(() {',
                      # Goldens are found beside the file that compares them.
                      "      goldenFileComparator = "
                      "LocalFileComparator(Uri.base.resolve('%s'));" % p]
            if widgets:
                lines.append('      _fresh();')
            lines += ['    });', '    t%d.main();' % i, '  });']
        lines.append('}')
        if widgets:
            lines += ['',
                      '/// The test window as a new process has it: what a file before',
                      "/// set and didn't put back isn't this file's.",
                      'void _fresh() {',
                      '  final dispatcher =',
                      '      TestWidgetsFlutterBinding.instance.platformDispatcher;',
                      '  dispatcher.clearAllTestValues();',
                      '  for (final view in dispatcher.views) {',
                      '    view.reset();',
                      '  }',
                      '}']
        path = os.path.join(OUT, bundle + '.dart')
        with open(path, 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines) + '\n')
        bundles[path] = paths
    return bundles, alone


def failed_files(report, bundles):
    """From a JSON report: the test files with a failure, and the bundles
    that didn't load (each file of theirs runs again)."""
    suites, names, failed = {}, {}, set()
    for line in open(report, encoding='utf-8'):
        try:
            event = json.loads(line)
        except ValueError:
            continue
        kind = event.get('type')
        if kind == 'suite':
            suites[event['suite']['id']] = os.path.relpath(event['suite']['path'], APP)
        elif kind == 'testStart':
            test = event['test']
            names[test['id']] = (suites.get(test['suiteID'], ''), test['name'])
        elif kind in ('testDone', 'error'):
            if kind == 'testDone' and event.get('result') == 'success':
                continue
            suite, name = names.get(event.get('testID'), ('', ''))
            if suite in bundles:
                # Named "<file> <test>" by its group; else it's the bundle's
                # own loading or a hook outside every group.
                first = name.split(' ', 1)[0]
                path = 'test/' + first
                failed.update([path] if path in bundles[suite] else bundles[suite])
            elif suite:
                failed.add(suite)
    return failed


def main():
    args = sys.argv[1:]
    widget_bundles = 8
    if args[:1] == ['--bundles']:
        widget_bundles = int(args[1])
        args = args[2:]
    if not any(a.startswith(('--concurrency', '-j')) for a in args):
        args = ['--concurrency', '2'] + args
    os.chdir(APP)

    bundles, alone = bundle_files(widget_bundles)
    counted = sum(len(p) for p in bundles.values())
    print('app-test: %d files in %d bundles, %d alone'
          % (counted, len(bundles), len(alone)), flush=True)

    report = tempfile.NamedTemporaryFile(suffix='.json', delete=False).name
    try:
        first = subprocess.call(['flutter', 'test', *args, '--file-reporter',
                                 'json:' + report, *bundles, *alone])
        failed = failed_files(report, bundles)
    finally:
        os.remove(report)

    bundled = sorted(f for f in failed if f not in alone)
    real = sorted(f for f in failed if f in alone)
    if first != 0 and not failed:
        print('app-test: flutter test failed before any test did', flush=True)
        return first
    if not bundled:
        return 1 if real else 0

    print('\napp-test: %d file(s) had failures in their bundle; each runs '
          'again on its own, and that result counts:' % len(bundled), flush=True)
    for path in bundled:
        print('  ' + path, flush=True)
    again = subprocess.call(['flutter', 'test', *args, *bundled])
    if again == 0:
        print('\napp-test: on their own they all pass: what failed came from '
              'sharing a process with other files.', flush=True)
    else:
        print('\napp-test: they fail on their own too (above).', flush=True)
    if real:
        print('app-test: files run alone failed: ' + ', '.join(real), flush=True)
    return 1 if again != 0 or real else 0


if __name__ == '__main__':
    sys.exit(main())
