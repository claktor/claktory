#!/bin/sh
# Builds a debug Windows app (x64) on a Mac, for a Windows machine without
# Visual Studio's build tools yet: the runner and its plugin compiled with
# clang-cl and linked with lld-link against Windows' libraries from
# cargo-xwin's cache, Flutter's debug engine for Windows, and the Dart code
# as a debug kernel (JIT, as `flutter run` gives). The C runtime is linked
# in (/MT), as the engine's is, so it runs without the Visual C++
# Redistributable.
#
#   app/windows/tool/cross_build.sh          Claktory Dev, the debug flavor
#   app/windows/tool/cross_build.sh --dev    Claktory Dev for the dev Claktory
#
# The debug flavor also builds windows_smoke.exe beside the app
# (test/windows_smoke.cpp: the private folder, DPAPI and the store on
# Windows itself, no window).
#
# It leaves the app in app/build/windows-cross/Claktory (Claktory.exe and
# what it needs beside it) and a zip of it beside that folder, with its
# SHA-256 printed.
#
# What it leaves out: the private tunnel (app/rust, through the build hook,
# which looks for Visual Studio), so connecting through it fails on such a
# build; everything else in the app is there. The Windows build itself
# (flutter build windows, on Windows) has it all and decides.
#
# Environment: CLANG_CL, LLD_LINK (Homebrew's lld), XWIN and FLUTTER_HEADERS as check_compile.sh;
# ENGINE_CACHE (default ~/Library/Caches/claktory-windows/engine-<engine>),
# where Flutter's Windows engine is kept once fetched.
set -eu

flavor=debug
[ "${1:-}" = "--dev" ] && flavor=dev

windows=$(cd "$(dirname "$0")/.." && pwd)
app=$(dirname "$windows")
llvm=/opt/homebrew/opt/llvm/bin
clang_cl=${CLANG_CL:-$llvm/clang-cl}
lld_link=${LLD_LINK:-$(command -v lld-link || echo "$llvm/lld-link")}
xwin=${XWIN:-$HOME/Library/Caches/cargo-xwin/xwin}
for tool in "$clang_cl" "$lld_link" "$llvm/llvm-rc"; do
  [ -x "$tool" ] || { echo "missing $tool"; exit 2; }
done
[ -d "$xwin/sdk/include/um" ] || { echo "no Windows headers at $xwin (XWIN)"; exit 2; }

flutter_root=$(dirname "$(dirname "$(readlink -f "$(command -v flutter)")")")
engine=$(cat "$flutter_root/bin/internal/engine.version")
cache=${ENGINE_CACHE:-$HOME/Library/Caches/claktory-windows/engine-$engine}
storage=https://storage.googleapis.com/flutter_infra_release/flutter/$engine
fetch() { # zip under $storage, folder in $cache
  [ -f "$cache/$2/.done" ] && return
  mkdir -p "$cache/$2"
  curl -sf "$storage/$1" -o "$cache/$2.zip"
  unzip -qo "$cache/$2.zip" -d "$cache/$2"
  rm -f "$cache/$2.zip" "$cache/$2"/*.pdb
  touch "$cache/$2/.done"
}
fetch windows-x64-debug/windows-x64-flutter.zip engine
fetch windows-x64/flutter-cpp-client-wrapper.zip wrapper
fetch windows-x64/artifacts.zip artifacts
wrapper=$cache/wrapper/cpp_client_wrapper

out=$app/build/windows-cross
objects=$out/obj-$flavor
bundle=$out/Claktory
rm -rf "$objects" "$bundle"
mkdir -p "$objects" "$bundle/data/flutter_assets"

# The Dart side: a debug kernel, with the Windows plugins' Dart halves
# registered as Flutter's own registrant does.
dart_defines=""
[ "$flavor" = dev ] && dart_defines="-DFACTORY_DEV=true"
registrant=$objects/dart_plugin_registrant.dart
cat >"$registrant" <<'EOF'
// Generated by app/windows/tool/cross_build.sh, as Flutter's own.
import 'dart:io';
import 'package:url_launcher_windows/url_launcher_windows.dart' as url_launcher_windows;

@pragma('vm:entry-point')
class _PluginRegistrant {
  @pragma('vm:entry-point')
  static void register() {
    if (Platform.isWindows) {
      url_launcher_windows.UrlLauncherWindows.registerWith();
    }
  }
}
EOF
cache_bin=$flutter_root/bin/cache
(cd "$app" && flutter pub get >/dev/null)
(cd "$app" && git checkout -q analysis_options.yaml 2>/dev/null || true)
"$cache_bin/dart-sdk/bin/dartaotruntime" \
  "$cache_bin/dart-sdk/bin/snapshots/frontend_server_aot.dart.snapshot" \
  --sdk-root "$cache_bin/artifacts/engine/common/flutter_patched_sdk/" \
  --target=flutter --no-print-incremental-dependencies \
  -Ddart.vm.profile=false -Ddart.vm.product=false --enable-asserts \
  --track-widget-creation --no-link-platform \
  $dart_defines \
  --packages "$app/.dart_tool/package_config.json" \
  --output-dill "$bundle/data/flutter_assets/kernel_blob.bin" \
  --source "file://$registrant" \
  --source package:flutter/src/dart_plugin_registrant.dart \
  "-Dflutter.dart_plugin_registrant=file://$registrant" \
  --verbosity=error \
  "package:factory_app/main.dart"

# Its assets: the fonts (pubspec.yaml), their manifests.
python3 - "$app" "$bundle/data/flutter_assets" <<'EOF'
import json, os, re, shutil, struct, sys
app, assets = sys.argv[1], sys.argv[2]
pubspec = open(os.path.join(app, "pubspec.yaml")).read()
families, family = [], None
for line in pubspec.splitlines():
    m = re.match(r"\s*- family:\s*(\S+)", line)
    if m:
        family = {"family": m.group(1), "fonts": []}
        families.append(family)
        continue
    m = re.match(r"\s*- asset:\s*(\S+)", line)
    if m and family is not None:
        family["fonts"].append({"asset": m.group(1)})
        continue
    m = re.match(r"\s*(style|weight):\s*(\S+)", line)
    if m and family is not None and family["fonts"]:
        value = m.group(2)
        family["fonts"][-1][m.group(1)] = int(value) if value.isdigit() else value
files = [f["asset"] for fam in families for f in fam["fonts"]]
for path in files:
    os.makedirs(os.path.dirname(os.path.join(assets, path)), exist_ok=True)
    shutil.copy(os.path.join(app, path), os.path.join(assets, path))
json.dump(families, open(os.path.join(assets, "FontManifest.json"), "w"))
# AssetManifest.bin: StandardMessageCodec's {asset: [{"asset": asset}]}.
def size(n):
    if n < 254: return bytes([n])
    if n <= 0xFFFF: return bytes([254]) + struct.pack("<H", n)
    return bytes([255]) + struct.pack("<I", n)
def string(s):
    b = s.encode("utf-8")
    return bytes([7]) + size(len(b)) + b
out = bytes([13]) + size(len(files))
for path in files:
    out += string(path) + bytes([12]) + size(1) + bytes([13]) + size(1)
    out += string("asset") + string(path)
open(os.path.join(assets, "AssetManifest.bin"), "wb").write(out)
EOF

# The native side.
real=0
dev=0
[ "$flavor" = dev ] && dev=1
version=$(sed -n 's/^version: *//p' "$app/pubspec.yaml")
version=${version%%+*}
major=${version%%.*}; rest=${version#*.}; minor=${rest%%.*}; patch=${rest#*.}
includes="/imsvc $xwin/crt/include /imsvc $xwin/sdk/include/ucrt /imsvc $xwin/sdk/include/um /imsvc $xwin/sdk/include/shared /imsvc $xwin/sdk/include/winrt"
compile() { # source, object, extra flags...
  source=$1; object=$2; shift 2
  "$clang_cl" --target=x86_64-pc-windows-msvc -fms-compatibility-version=19.40 \
    /std:c++17 /W4 /WX /wd4100 /EHsc /MT /O1 /Zc:__cplusplus \
    -Wno-unused-command-line-argument \
    /D_HAS_EXCEPTIONS=0 /DUNICODE /D_UNICODE /DNOMINMAX \
    /D_WIN32_WINNT=0x0A00 /DWINVER=0x0A00 /DNTDDI_VERSION=0x0A00000B \
    $includes /I "$cache/engine" /I "$wrapper/include" "$@" \
    /c "/Fo$object" -- "$source"
}
for source in "$wrapper"/core_implementations.cc "$wrapper"/standard_codec.cc \
  "$wrapper"/flutter_engine.cc "$wrapper"/flutter_view_controller.cc \
  "$wrapper"/plugin_registrar.cc; do
  compile "$source" "$objects/wrapper_$(basename "$source" .cc).obj" -Wno-everything
done
plugin=$(cd "$app" && jq -r '.packages[] | select(.name=="url_launcher_windows") | .rootUri' .dart_tool/package_config.json | sed 's|^file://||')
for source in "$plugin"/windows/*.cpp; do
  compile "$source" "$objects/plugin_$(basename "$source" .cpp).obj" \
    /DFLUTTER_PLUGIN_IMPL /I "$plugin/windows/include" -Wno-everything
done
for source in "$windows"/runner/*.cpp "$windows"/runner/core/*.cpp \
  "$windows"/flutter/generated_plugin_registrant.cc; do
  name=$(basename "$source"); name=${name%.*}
  # The plugin is linked in, not a DLL beside: its functions aren't imported.
  compile "$source" "$objects/runner_$name.obj" /DFLUTTER_PLUGIN_IMPL \
    "/DCLAKTORY_FLAVOR_REAL=$real" "/DCLAKTORY_FLAVOR_DEV=$dev" \
    /I "$windows/runner" /I "$windows" /I "$plugin/windows/include"
done
# From its folder: llvm-rc would read an input path starting with /U as an
# option. Its copy says resources/ for resources\\, which the Mac's file
# system doesn't take.
sed 's|resources\\\\|resources/|g' "$windows/runner/Runner.rc" >"$windows/runner/.Runner.cross.rc"
(cd "$windows/runner" && "$llvm/llvm-rc" /nologo /DUNICODE /D_UNICODE \
  "/DCLAKTORY_FLAVOR_REAL=$real" "/DCLAKTORY_FLAVOR_DEV=$dev" \
  "/DFLUTTER_VERSION=\"$version\"" "/DFLUTTER_VERSION_MAJOR=$major" \
  "/DFLUTTER_VERSION_MINOR=$minor" "/DFLUTTER_VERSION_PATCH=$patch" \
  /DFLUTTER_VERSION_BUILD=0 \
  /I "$xwin/sdk/include/um" /I "$xwin/sdk/include/shared" \
  /I "$xwin/crt/include" /I "$xwin/sdk/include/ucrt" /I "$windows/runner" \
  /FO "$objects/Runner.res" .Runner.cross.rc)
rm -f "$windows/runner/.Runner.cross.rc"
"$lld_link" /nologo /NOIMPLIB /NOEXP /OUT:"$bundle/Claktory.exe" /SUBSYSTEM:WINDOWS \
  /MANIFEST:EMBED /MANIFESTINPUT:"$windows/runner/runner.exe.manifest" \
  /MANIFESTUAC:"level='asInvoker' uiAccess='false'" \
  /LIBPATH:"$xwin/crt/lib/x86_64" /LIBPATH:"$xwin/sdk/lib/um/x86_64" \
  /LIBPATH:"$xwin/sdk/lib/ucrt/x86_64" \
  "$objects"/*.obj "$objects/Runner.res" "$cache/engine/flutter_windows.dll.lib" \
  dwmapi.lib crypt32.lib shell32.lib ole32.lib advapi32.lib uuid.lib \
  iphlpapi.lib runtimeobject.lib wtsapi32.lib shlwapi.lib user32.lib \
  gdi32.lib kernel32.lib comdlg32.lib oleaut32.lib \
  libcmt.lib libcpmt.lib libvcruntime.lib libucrt.lib

# The smoke test: the runner's files on disk, checked on Windows itself.
compile "$windows/test/windows_smoke.cpp" "$objects/smoke_main.obj" \
  /DCLAKTORY_FLAVOR_REAL=0 /DCLAKTORY_FLAVOR_DEV=0 \
  /I "$windows/runner" /I "$windows"
smoke_objects=""
for name in app_paths file_store utils connection_store json window_geometry; do
  smoke_objects="$smoke_objects $objects/runner_$name.obj"
done
if [ "$flavor" = debug ]; then
  "$lld_link" /nologo /NOIMPLIB /NOEXP /OUT:"$bundle/windows_smoke.exe" \
    /SUBSYSTEM:CONSOLE \
    /LIBPATH:"$xwin/crt/lib/x86_64" /LIBPATH:"$xwin/sdk/lib/um/x86_64" \
    /LIBPATH:"$xwin/sdk/lib/ucrt/x86_64" \
    "$objects/smoke_main.obj" $smoke_objects "$cache/engine/flutter_windows.dll.lib" \
    crypt32.lib shell32.lib ole32.lib advapi32.lib user32.lib kernel32.lib \
    libcmt.lib libcpmt.lib libvcruntime.lib libucrt.lib
fi

cp "$cache/engine/flutter_windows.dll" "$bundle/"
cp "$cache/artifacts/icudtl.dat" "$bundle/data/"
cp "$windows/runner/resources/notification_icon.png" \
  "$windows/runner/resources/notification_icon_dev.png" "$bundle/data/"

# A build of uncommitted changes says so in its name.
commit=$(cd "$app" && git rev-parse --short HEAD)
[ -n "$(cd "$app" && git status --porcelain -- .)" ] && commit="$commit-dirty"
zip_name="Claktory-windows-x64-$flavor-$commit.zip"
rm -f "$out"/Claktory-windows-x64-*.zip
(cd "$out" && zip -qr "$zip_name" Claktory)
echo "$out/$zip_name"
shasum -a 256 "$out/$zip_name"
